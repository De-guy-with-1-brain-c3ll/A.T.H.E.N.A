"""Measure every DashScope ASR model with real audio and a known transcript.

Audio is generated by the cloud voice from text we control, then fed back through
each recogniser. That gives a ground truth to score against, so "which model is
better" becomes a number rather than an impression.

The sentences deliberately include the things that have gone wrong in real use:
"CJ" (the word that kept arriving as "Jesus"), numbers, hyphenated course names,
and Chinese words mixed into English.

    ./.venv/Scripts/python.exe tools/bench_stt.py
    ./.venv/Scripts/python.exe tools/bench_stt.py --models qwen-audio-3.0-asr-flash-streaming
"""
from __future__ import annotations

import argparse
import asyncio
from dataclasses import dataclass, field
import json
import os
from pathlib import Path
import re
import sys
import time
from uuid import uuid4

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from athena.config import ASR_MODELS, load_local_environment

SAMPLE_RATE = 16000
TTS_SAMPLE_RATE = 24000
SPEAK_TURN_TIMEOUT = 45.0

# Ground truth. "CJ" is the recurring failure; "Pre-Calculus" and "CodeHS" are
# domain words no general model knows; the last one is genuine code-switching.
SENTENCES = {
    "cj": "The meeting with CJ is at four thirty this afternoon.",
    "network": "CJ asked whether the network hackers club meets on Thursday.",
    "numbers": "The temperature is 71.4 degrees and the humidity is 58 percent.",
    "courses": "I have a Pre-Calculus assignment due Friday and a CodeHS lesson to finish.",
    "mixed": "Tell CJ 我下午四点开会, and remind me about the thermostat.",
    "long": (
        "Good morning. You have three things today: the network meeting with CJ at "
        "four thirty, a Pre-Calculus assignment due Friday, and the thermostat is "
        "holding at seventy two degrees. I have saved a brief for each."
    ),
}

# Languages to try per sentence. The mixed sentence needs both hints.
LANGUAGES = {
    "cj": ["en"],
    "network": ["en"],
    "numbers": ["en"],
    "courses": ["en"],
    "mixed": ["en", "en,zh"],
    "long": ["en"],
}


_NUMBER_WORDS = {
    "zero": 0, "one": 1, "two": 2, "three": 3, "four": 4, "five": 5, "six": 6,
    "seven": 7, "eight": 8, "nine": 9, "ten": 10, "eleven": 11, "twelve": 12,
    "thirteen": 13, "fourteen": 14, "fifteen": 15, "sixteen": 16, "seventeen": 17,
    "eighteen": 18, "nineteen": 19, "twenty": 20, "thirty": 30, "forty": 40,
    "fifty": 50, "sixty": 60, "seventy": 70, "eighty": 80, "ninety": 90,
}

# Recognisers render numbers as digits ("4.30", "71.4"), and sometimes glue a
# decimal point where a spoken number was split. Comparing those two forms textually
# counts a correct transcription as several errors, which is the scorer's fault,
# not the model's.
_SOUND_ALIKE = {
    "4.30": {"four", "thirty", "four thirty"},
    "4": {"four"},
    "30": {"thirty"},
}


def words_for(text: str) -> list[str]:
    """Split into comparable tokens, treating "4.30" as "four thirty"."""
    tokens: list[str] = []
    for raw in normalise(text).split():
        # A dotted number like 4.30 or 71.4 becomes its spoken parts.
        if re.fullmatch(r"\d+(?:\.\d+)?", raw):
            head, _, tail = raw.partition(".")
            if tail:
                # 4.30 -> four thirty; 71.4 -> seventy one (point) four
                as_int = int(head)
                for part in _int_to_words(as_int):
                    tokens.append(part)
                for digit in tail:
                    if digit == "0" and len(tail) == 2:
                        continue  # "30" is thirty, not three zero
                if tail in ("30", "20", "40", "50", "60", "70", "80", "90"):
                    tokens.append(_tens_word(tail))
                else:
                    for digit in tail:
                        tokens.append(_digit_word(digit))
            else:
                tokens.extend(_int_to_words(int(head)))
        else:
            tokens.append(raw)
    return tokens


def _digit_word(digit: str) -> str:
    for word, value in _NUMBER_WORDS.items():
        if len(word) > 3 and value < 10 and word == digit:
            return word
    return {"0": "zero", "1": "one", "2": "two", "3": "three", "4": "four",
            "5": "five", "6": "six", "7": "seven", "8": "eight",
            "9": "nine"}.get(digit, digit)


def _tens_word(tail: str) -> str:
    return {"20": "twenty", "30": "thirty", "40": "forty", "50": "fifty",
            "60": "sixty", "70": "seventy", "80": "eighty",
            "90": "ninety"}.get(tail, tail)


def _int_to_words(value: int) -> list[str]:
    if value < 20:
        for word, number in _NUMBER_WORDS.items():
            if number == value:
                return [word]
        return [str(value)]
    tens, ones = divmod(value, 10)
    words = [_tens_word(str(tens * 10))]
    if ones:
        words.append(_digit_word(str(ones)))
    return words


def normalise(text: str) -> str:
    """Compare on words, ignoring punctuation, case and spacing."""
    text = text.casefold()
    text = re.sub(r"[^\w\s]", " ", text)
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def word_error_rate(reference: str, hypothesis: str) -> tuple[float, list[str]]:
    """Levenshtein distance over words, divided by reference length."""
    ref = words_for(reference)
    hyp = words_for(hypothesis)
    if not ref:
        return (0.0 if not hyp else 1.0), []
    # Standard edit distance over the word sequences.
    previous = list(range(len(hyp) + 1))
    for i, rword in enumerate(ref, 1):
        current = [i]
        for j, hword in enumerate(hyp, 1):
            cost = 0 if rword == hword else 1
            current.append(min(previous[j] + 1,      # deletion
                               current[j - 1] + 1,    # insertion
                               previous[j - 1] + cost))  # substitution
        previous = current
    errors = []
    # Report which reference words are missing, which is the actionable part.
    hyp_set = set(hyp)
    for word in ref:
        if word not in hyp_set:
            errors.append(word)
    return previous[-1] / len(ref), errors


async def synthesize(text: str) -> bytes:
    """Produce 24 kHz PCM for the text using the cloud voice."""
    from athena.tts.qwen import QwenRealtimeSynthesizer

    speaker = QwenRealtimeSynthesizer(
        os.environ["DASHSCOPE_API_KEY"], "qwen3-tts-flash-realtime", "Neil")

    class Store:
        def get(self, key, default=None):
            return 1.2 if key == "tts_speech_rate" else default

    speaker._settings = Store()
    turn = uuid4()
    pcm = b""
    try:
        await speaker.connect()
        await speaker.send_text(turn, text)
        await speaker.flush(turn)
        async for chunk in speaker.audio(turn):
            pcm += chunk.pcm
    finally:
        try:
            await speaker.close()
        except Exception:
            pass
    return pcm


def resample_24k_to_16k(pcm: bytes) -> bytes:
    """24 kHz -> 16 kHz by dropping frames, with a light average to avoid aliasing.

    The recognisers are all configured for 16 kHz. Feeding 24 kHz audio in makes
    speech 1.5x too fast, which is a real trap: it still transcribes well enough to
    look fine, so the mistake hides.
    """
    import array

    source = array.array("h")
    source.frombytes(pcm[: len(pcm) - (len(pcm) % 2)])
    # Keep two samples then drop one: exactly 3:2, giving 16 kHz from 24 kHz.
    out = array.array("h")
    i = 0
    while i + 2 < len(source):
        out.append((source[i] + source[i + 1]) // 2)
        out.append(source[i + 2])
        i += 3
    return out.tobytes()


async def recognise(model: str, pcm: bytes, languages: list[str]) -> dict:
    """Run one recogniser over one clip and return the transcript and timing."""
    from athena.stt.fun_asr import FunAsrRecognizer

    recognizer = FunAsrRecognizer(
        api_key=os.environ["DASHSCOPE_API_KEY"],
        model=model,
        sample_rate=SAMPLE_RATE,
        language=languages[0],
        prewarm=False,
    )
    recognizer._languages = languages
    turn = uuid4()
    # Streaming returns cumulative partials ("The me", "The meeting with seed",
    # ...), each replacing the last. Keeping only the newest is what the
    # coordinator effectively uses; concatenating them would score the same words
    # many times over and make every model look terrible.
    latest: list[str] = []
    is_final_seen = False
    first_result_at: float | None = None
    started = time.perf_counter()
    try:
        await recognizer.connect()
        await recognizer.start_turn(turn)

        async def feed() -> None:
            # 100 ms per packet, as the service expects.
            step = 3200
            for offset in range(0, len(pcm), step):
                await recognizer.send_audio(pcm[offset:offset + step])
            await recognizer.finish_turn()

        async def collect() -> None:
            nonlocal first_result_at, is_final_seen
            async for transcript in recognizer.results():
                if transcript.turn_id != turn:
                    continue
                if first_result_at is None:
                    first_result_at = time.perf_counter() - started
                text = (transcript.text or "").strip()
                # The recogniser marks the end of a turn with a sentinel rather
                # than an exception, so it has to be filtered out of the text
                # instead of being fed to the scorer.
                if text.startswith("[STT complete]") or text.startswith("[STT error]"):
                    if text.startswith("[STT error]"):
                        raise RuntimeError(text)
                    return
                if text:
                    latest[:] = [text]
                if transcript.is_final:
                    is_final_seen = True
                    return

        # Bound the whole thing: without it a session that never completes waits
        # forever and the benchmark produces no output at all.
        await asyncio.wait_for(asyncio.gather(feed(), collect()),
                               timeout=SPEAK_TURN_TIMEOUT)
        total = time.perf_counter() - started
        return {"ok": True, "text": latest[-1] if latest else "", "total": total,
                "first": first_result_at,
                "connect_ms": recognizer.last_connect_ms,
                "is_final": is_final_seen,
                "audio_s": len(pcm) / 2 / SAMPLE_RATE}
    except Exception as error:  # noqa: BLE001 - a rejected model is a result
        return {"ok": False, "error": f"{type(error).__name__}: {error}",
                "total": time.perf_counter() - started}
    finally:
        try:
            await recognizer.close()
        except Exception:
            pass


async def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--models", nargs="*", default=list(ASR_MODELS))
    parser.add_argument(
        "--sentences", nargs="*", choices=tuple(SENTENCES),
        default=list(SENTENCES),
        help="controlled sentence ids to synthesize and recognise",
    )
    parser.add_argument("--out", default="outputs/audio-tests")
    args = parser.parse_args()

    load_local_environment()
    if not os.environ.get("DASHSCOPE_API_KEY"):
        print("DASHSCOPE_API_KEY is not set.", file=sys.stderr)
        return 1

    out = Path(args.out)
    clips = out / "stt-clips"
    clips.mkdir(parents=True, exist_ok=True)

    print("Generating reference audio with the cloud voice...")
    audio: dict[str, bytes] = {}
    for name in args.sentences:
        print(f"  synthesising {name} ...", flush=True)
        pcm24 = await synthesize(SENTENCES[name])
        pcm16 = resample_24k_to_16k(pcm24)
        audio[name] = pcm16
        # Keep the audio for listening back to.
        import wave
        with wave.open(str(clips / f"{name}.wav"), "wb") as handle:
            handle.setnchannels(1)
            handle.setsampwidth(2)
            handle.setframerate(SAMPLE_RATE)
            handle.writeframes(pcm16)
        print(f"  {name:<10} {len(pcm16) / 2 / SAMPLE_RATE:.2f}s of 16 kHz audio")

    results: list[dict] = []
    print()
    header = (f"{'model':<38} {'sentence':<10} {'wer':>6} {'first':>7} "
              f"{'total':>7}  transcript")
    for model in args.models:
        print("=" * 78)
        print(model)
        print("=" * 78)
        print(header)
        print("-" * 78)
        for name in args.sentences:
            try:
                outcome = await recognise(model, audio[name], LANGUAGES[name])
            except ValueError as error:
                # The 8k model refuses non-Chinese outright, which is a fact about
                # the model worth reporting rather than a crash.
                print(f"{model:<38} {name:<10}  ---  not applicable: {error}")
                results.append({"model": model, "sentence": name, "ok": False,
                                "error": f"not applicable: {error}"})
                continue
            if not outcome["ok"]:
                print(f"{model:<38} {name:<10}  ---  FAILED: {outcome['error'][:40]}")
                results.append({"model": model, "sentence": name, "ok": False,
                                "error": outcome["error"]})
                continue
            wer, missing = word_error_rate(SENTENCES[name], outcome["text"])
            first = outcome["first"] or 0.0
            print(f"{model:<38} {name:<10} {wer:>6.2f} {first:>6.2f}s "
                  f"{outcome['total']:>6.2f}s  {outcome['text'][:60]}")
            results.append({
                "model": model, "sentence": name, "ok": True,
                "reference": SENTENCES[name], "hypothesis": outcome["text"],
                "wer": round(wer, 3), "missing_words": missing,
                "first_result_s": round(first, 3),
                "total_s": round(outcome["total"], 3),
                "audio_s": round(outcome["audio_s"], 3),
            })
        print()

    _report(results, ASR_MODELS)
    path = out / "stt-results.json"
    path.write_text(json.dumps({"results": results}, indent=2))
    print(f"raw results -> {path}")
    return 0


def _report(results: list[dict], catalog: dict) -> None:
    good = [r for r in results if r.get("ok")]
    print("=" * 78)
    print("SUMMARY BY MODEL")
    print("=" * 78)
    print(f"{'model':<38} {'mean WER':>9} {'first':>8} {'cost/hour':>10}  note")
    print("-" * 78)
    by_model: dict[str, list[dict]] = {}
    for row in good:
        by_model.setdefault(row["model"], []).append(row)
    for model in catalog:
        rows = by_model.get(model)
        if not rows:
            print(f"{model:<38} {'---':>9} {'---':>8} {'---':>10}  no successful run")
            continue
        mean_wer = sum(r["wer"] for r in rows) / len(rows)
        mean_first = sum(r["first_result_s"] for r in rows) / len(rows)
        price, note = catalog[model]
        per_hour = price * 3600
        print(f"{model:<38} {mean_wer:>9.3f} {mean_first:>7.2f}s "
              f"{per_hour:>9.2f}  {note[:38]}")

    # The words that go missing are the actionable finding.
    print()
    print("Words the recognisers dropped")
    print("-" * 78)
    dropped: dict[str, set[str]] = {}
    for row in good:
        for word in row["missing_words"]:
            dropped.setdefault(word, set()).add(row["model"])
    if not dropped:
        print("  none — every reference word was heard by at least one model")
    for word, models in sorted(dropped.items()):
        if len(models) == 1:
            only = next(iter(models))
            print(f"  {word:<16} missed only by {only}")
        else:
            print(f"  {word:<16} missed by {len(models)} models")


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
